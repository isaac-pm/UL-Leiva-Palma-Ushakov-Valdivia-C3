# -----------------------------------------------------------------------------
# Zero-Memory Stream Cleaner (The fix for \x00 in File 56)
# -----------------------------------------------------------------------------
class CleanCSVStream:
    """
    Reads the file in 8KB chunks, stripping null bytes (\x00) instantly.
    Memory usage is flat and nearly zero, bypassing Python's memory limits.
    """
    def __init__(self, filepath):
        self.file = open(filepath, 'r', encoding='utf-8-sig')
        
    def read(self, size=8192):
        chunk = self.file.read(size)
        return chunk.replace('\x00', '') if chunk else ""
        
    def close(self):
        self.file.close()

